  /* ---------- custom cursor ---------- */
  const cursor = document.getElementById("cursor");
  const cursorLabel = document.getElementById("cursorLabel");
  let cursorActive = false;
  let hoverScale = 0.4;
  let targetX = window.innerWidth / 2, targetY = window.innerHeight / 2;
  let curX = targetX, curY = targetY;

  window.addEventListener("pointermove", e => {
    if (e.pointerType !== "mouse") return;
    targetX = e.clientX;
    targetY = e.clientY;
    if (!cursor.classList.contains("is-active")) cursor.classList.add("is-active");
  });

  function renderCursor(){
    curX += (targetX - curX) * 0.22;
    curY += (targetY - curY) * 0.22;
    const scale = cursorActive ? 1 : hoverScale;
    cursor.style.transform = `translate3d(${curX}px, ${curY}px, 0) scale(${scale})`;
    requestAnimationFrame(renderCursor);
  }
  requestAnimationFrame(renderCursor);

  function bindCursor(selector, label){
    document.querySelectorAll(selector).forEach(el => {
      el.addEventListener("mouseenter", () => {
        cursorActive = true;
        cursor.classList.add("is-hover");
        cursorLabel.textContent = label;
      });
      el.addEventListener("mouseleave", () => {
        cursorActive = false;
        cursor.classList.remove("is-hover");
        cursorLabel.textContent = "";
      });
    });
  }
  bindCursor(".g-card", "View");
  bindCursor(".v-card", "Play");
  bindCursor("a, button", "");

  /* ---------- contact form -> opens the visitor's email client, prefilled ---------- */
  const contactForm = document.getElementById("contactForm");
  const formNote = document.getElementById("formNote");
  const STUDIO_EMAIL = "rapisakentva@gmail.com";

  contactForm.addEventListener("submit", e => {
    e.preventDefault();
    const name = contactForm.name.value.trim();
    const email = contactForm.email.value.trim();
    const projectType = contactForm.projectType.value;
    const message = contactForm.message.value.trim();

    const subject = `New project inquiry — ${projectType}`;
    const body =
      `Name: ${name}\n` +
      `Email: ${email}\n` +
      `Project type: ${projectType}\n\n` +
      `${message}`;

    const mailtoLink = `mailto:${STUDIO_EMAIL}` +
      `?subject=${encodeURIComponent(subject)}` +
      `&body=${encodeURIComponent(body)}`;

    window.location.href = mailtoLink;

    formNote.textContent = "Opening your email app to send this — hit send there to reach us.";
    contactForm.reset();
  });

  /* ---------- utility ---------- */
  function escapeHtml(str){
    return String(str).replace(/[&<>"']/g, s => ({
      "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
    }[s]));
  }

